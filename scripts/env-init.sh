#!/usr/bin/env bash
# Prepare .env for local development.
#
#   scripts/env-init.sh                 create .env if it is missing
#   scripts/env-init.sh --fill-secrets  generate only the secrets that are
#                                       missing or still placeholders, leaving
#                                       every other line untouched
#   scripts/env-init.sh --force         replace .env entirely
#
# The service refuses to start without a usable MASTER_KEY and SESSION_SECRET,
# so this writes generated ones rather than the placeholders in .env.example.
# An existing .env is never overwritten by accident: provider credentials are
# encrypted under its MASTER_KEY and are unreadable without it.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

mode="create"
case "${1:-}" in
"") ;;
--fill-secrets) mode="fill" ;;
--force) mode="force" ;;
*) die "unknown option '${1}'. Use --fill-secrets or --force." ;;
esac

# valid_master_key reports whether a value decodes to exactly 32 bytes, which
# is what AES-256 needs and what the config loader checks.
valid_master_key() {
	local value="$1" decoded
	[[ -n "$value" ]] || return 1
	decoded="$(printf '%s' "$value" | base64 -d 2>/dev/null | wc -c | tr -d '[:space:]')" || return 1
	[[ "$decoded" == "32" ]]
}

valid_session_secret() {
	[[ "${#1}" -ge 32 ]]
}

backup_env() {
	local backup=".env.backup.$(date +%Y%m%d%H%M%S)"
	cp .env "$backup"
	log "kept a copy of the previous .env at $backup"
}

write_fresh_env() {
	local master_key session_secret postgres_port redis_port grafana_port otlp_grpc_port otlp_http_port

	master_key="$(random_base64 32)"
	session_secret="$(random_base64 48)"

	# Pick host ports the containers can actually publish on. A Postgres or
	# Redis already installed on this machine takes the default, and Docker's
	# publish then loses silently: connections reach the other server and fail
	# authentication instead of failing to connect.
	postgres_port="$(pick_port 5432)"
	redis_port="$(pick_port 6379)"

	grafana_port="$(pick_port 3000)"
	otlp_grpc_port="$(pick_port 4317)"
	otlp_http_port="$(pick_port 4318)"

	if [[ "$postgres_port" != "5432" ]]; then
		warn "port 5432 is already in use, so Postgres will be published on $postgres_port"
	fi
	if [[ "$redis_port" != "6379" ]]; then
		warn "port 6379 is already in use, so Redis will be published on $redis_port"
	fi

	cat >.env <<EOF
# Generated by scripts/env-init.sh for local development.
# Real secrets live here and this file is gitignored. See .env.example for
# every variable the service understands, including the Phase 2 and
# OpenTelemetry settings this file leaves out.

PORT=8080
APP_ENV=development
ALLOWED_ORIGINS=http://localhost:3000
PUBLIC_BASE_URL=http://localhost:8080

# Host ports the compose containers publish on, and the URLs that match them.
# Change all four together if you move a port.
#
# The _LOCAL suffix is what APP_ENV=development reads. A deployment sets
# DATABASE_URL and REDIS_URL instead, so a remote URL can sit beside these
# without either one quietly shadowing the other.
POSTGRES_PORT=$postgres_port
REDIS_PORT=$redis_port
DATABASE_URL_LOCAL=postgres://gateway:gateway@127.0.0.1:$postgres_port/llm_gateway?sslmode=disable
REDIS_URL_LOCAL=redis://127.0.0.1:$redis_port

# Generated, not placeholders: the service will not start without both.
MASTER_KEY=$master_key
SESSION_SECRET=$session_secret

SESSION_TTL=336h
SESSION_IDLE_TTL=24h
COOKIE_DOMAIN=

# No mail provider is wired yet, so verification and reset links are written
# to the service log.
MAIL_FROM=no-reply@localhost

SEMANTIC_CACHE=off
CONTEXT_HANDOFF=off

# Telemetry stays off until you start the local stack with "make obs-up" and
# uncomment the endpoint. The ports are where compose publishes Grafana and the
# OTLP receiver. Cloud settings and the sampler are in .env.example.
OTEL_SERVICE_NAME=llm-gateway
OTEL_EXPORTER_OTLP_PROTOCOL=http/protobuf
GRAFANA_PORT=$grafana_port
OTLP_GRPC_PORT=$otlp_grpc_port
OTLP_HTTP_PORT=$otlp_http_port
# OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:$otlp_http_port
EOF

	log "wrote .env with a fresh MASTER_KEY and SESSION_SECRET"
}

# fill_secrets rewrites only the two secret lines, so a .env holding real
# provider URLs and tokens keeps every one of them.
fill_secrets() {
	local current_master current_session
	current_master="$(sed -n 's/^[[:space:]]*MASTER_KEY=//p' .env | tail -1 | tr -d '\r')"
	current_session="$(sed -n 's/^[[:space:]]*SESSION_SECRET=//p' .env | tail -1 | tr -d '\r')"

	local need_master=0 need_session=0
	valid_master_key "$current_master" || need_master=1
	valid_session_secret "$current_session" || need_session=1

	if [[ "$need_master" -eq 0 && "$need_session" -eq 0 ]]; then
		log "MASTER_KEY and SESSION_SECRET are both usable; nothing to do"
		return 0
	fi

	# Replacing a MASTER_KEY that was in use would orphan anything encrypted
	# under it, so say so rather than doing it quietly.
	if [[ "$need_master" -eq 1 && -n "$current_master" ]]; then
		warn "the current MASTER_KEY is not 32 bytes of base64 and is being replaced"
		warn "any provider credential encrypted under it would become unreadable"
	fi

	backup_env

	local new_master new_session
	new_master="$(random_base64 32)"
	new_session="$(random_base64 48)"

	local tmp=".env.tmp.$$"
	local saw_master=0 saw_session=0 line
	: >"$tmp"

	while IFS= read -r line || [[ -n "$line" ]]; do
		case "${line%$'\r'}" in
		MASTER_KEY=*)
			saw_master=1
			if [[ "$need_master" -eq 1 ]]; then
				printf 'MASTER_KEY=%s\n' "$new_master" >>"$tmp"
			else
				printf '%s\n' "${line%$'\r'}" >>"$tmp"
			fi
			;;
		SESSION_SECRET=*)
			saw_session=1
			if [[ "$need_session" -eq 1 ]]; then
				printf 'SESSION_SECRET=%s\n' "$new_session" >>"$tmp"
			else
				printf '%s\n' "${line%$'\r'}" >>"$tmp"
			fi
			;;
		*)
			printf '%s\n' "${line%$'\r'}" >>"$tmp"
			;;
		esac
	done <.env

	if [[ "$saw_master" -eq 0 && "$need_master" -eq 1 ]]; then
		printf '\nMASTER_KEY=%s\n' "$new_master" >>"$tmp"
	fi
	if [[ "$saw_session" -eq 0 && "$need_session" -eq 1 ]]; then
		printf 'SESSION_SECRET=%s\n' "$new_session" >>"$tmp"
	fi

	mv "$tmp" .env

	[[ "$need_master" -eq 1 ]] && log "generated a new MASTER_KEY"
	[[ "$need_session" -eq 1 ]] && log "generated a new SESSION_SECRET"
	log "every other line in .env is unchanged"
}

case "$mode" in
create)
	if [[ -f .env ]]; then
		log ".env already exists; leaving it alone"

		# Checking is free, and a placeholder secret stops the service from
		# starting at all, so point at the fix now rather than at startup.
		master="$(sed -n 's/^[[:space:]]*MASTER_KEY=//p' .env | tail -1 | tr -d '\r')"
		session="$(sed -n 's/^[[:space:]]*SESSION_SECRET=//p' .env | tail -1 | tr -d '\r')"
		if ! valid_master_key "$master" || ! valid_session_secret "$session"; then
			warn "MASTER_KEY or SESSION_SECRET is missing or still a placeholder, and the service will refuse to start"
			warn "run 'make env-secrets' to generate just those two, keeping everything else"
			exit 1
		fi
		log "its MASTER_KEY and SESSION_SECRET are usable"
		exit 0
	fi
	write_fresh_env
	log 'next: make deps-up && make run'
	;;
fill)
	[[ -f .env ]] || die "there is no .env yet. Run 'make env' first."
	fill_secrets
	;;
force)
	if [[ -f .env ]]; then
		backup_env
		warn "replacing .env; anything encrypted under the old MASTER_KEY needs that backup"
	fi
	write_fresh_env
	;;
esac
